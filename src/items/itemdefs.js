// weapons are items too (carried in slots, not weight)
for (const w of Object.values(WEAPONS))
  ITEMS[w.id] = I(w.id, w.name, w.cls === "MELEE" ? "melee" : "weapon", 0);
for (const [id, a] of Object.entries(ATTACHMENTS)) a.id = id;

export function attachmentFits(attId, weaponId) {
  const a = ATTACHMENTS[attId];
  const w = WEAPONS[weaponId];
  if (!a || !w) return false;
  return a.fits.includes(w.cls) && w.slots.includes(a.slot);
}

