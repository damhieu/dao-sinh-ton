export function makeNames(rng, n, exclude = "") {
  const pool = rng.shuffle(BASE.filter((s) => s !== exclude).slice());
  const out = [];
  for (let i = 0; i < n; i++) {
    const base = pool[i % pool.length];
    out.push(i < pool.length ? base : `${base}${rng.int(2, 99)}`);
  }
  return out;
}
